  async function init() {
    if (!isNakaEnabled)
      return logger.log('NAKA support not enabled, skipping naka store init')

    const dbCards = await getAllNakaCards()
    if (dbCards.length === 0) {
      // Get the cards from the API (used when login)
      logger.log('No card found in DB, getting it from the server')
      await until(isAppStarting).toBe(false)
      const user = await getUserStatus()
      if (user.identifications.some(identification => identification.status === 'VERIFIED'))
        await setupCard(user)
      else
        return
    }

    if (dbCards.length === 1) {
      logger.log('One card found in DB, using it', { dbCards })
      card.value = dbCards[0]
    }
    else {
      dbCards.sort((a, b) => {
        // Sort descending (latest expiry first)
        return (b.expiry.year - a.expiry.year) || (b.expiry.month - a.expiry.month)
      })
      if (dbCards[0]?.statusId === 'ACTIVE') {
        logger.log('Multiple cards found in DB, using the newest one', { dbCards })
        // Use the newest card
        card.value = dbCards[0]
      }
    }

    logger.log('init', card.value)
    if (!card.value)
      return

    if (card.value.statusId === 'ACTIVE') {
      // Check expiry
      if (isCardExpired(card.value)) {
        logger.log('Card expired', card.value.expiry)
        card.value.statusId = 'EXPIRED'
        await insertNakaCard(card.value)
      }
    }
  }

  async function updateUser() {
    // Check user status against issuer API
    const user = await getUserStatus()
    registration.value = {
      state: user.state,
      nakaIdentification: user.identifications.find(i => i.provider === 'NAKA-SUMSUB'),
      nakaCards: user.naka?.cards.map(nakaCardFromApi) || [],
    }

    if (!registration.value.nakaCards.length) {
      await purgeNakaCards()
      card.value = undefined
      return
    }

    // Update local card data
    card.value = registration.value.nakaCards.find(c => c.statusId === 'ACTIVE')
      // If not found, use the newest one
      || registration.value.nakaCards.sort((a, b) => {
        // Sort ascending (oldest expiry first)
        return (a.expiry.year - b.expiry.year) || (a.expiry.month - b.expiry.month)
      }).at(-1)!

    if (card.value.statusId === 'ACTIVE' && isCardExpired(card.value)) {
      logger.log('Card expired', card.value.expiry)
      card.value.statusId = 'EXPIRED'
    }

    cardBlockedCount.value = registration.value.nakaCards.filter(c => c.statusId === 'BLOCKED').length

    await insertNakaCard(card.value)
  }

  function isCardExpired(card: NakaCard): boolean {
    return card.expiry.year < new Date().getUTCFullYear()
      || (
        card.expiry.year === new Date().getUTCFullYear()
        && card.expiry.month < new Date().getUTCMonth() + 1
      )
  }

  /**
   * Registers the user in the issuer server and if the user has any cards, saves the active card in the store and db.
   */
  async function setupCard(user: UserStatusResponse) {
    const registration = await registerForNaka() // Only passes when the user has a VERIFIED identification
    return updateRegistration(user, registration)
  }

  async function issueNewCard(user: UserStatusResponse) {
    const registration = await issueCard()
    return updateRegistration(user, registration)
  }

  async function updateRegistration(user: UserStatusResponse, registration: NakaRegistrationResponse) {
    const { setRegistration, setCard } = useNaka()
    setRegistration({
      state: user.state,
      nakaIdentification: user.identifications.find(i => i.id === registration.identification),
      nakaCards: registration.cards.map(nakaCardFromApi),
    })

    if (registration.cards.length > 0) {
      const cards = registration.cards.map(nakaCardFromApi).filter(x => x.statusId === 'ACTIVE').sort((a, b) => {
        // Sort descending (latest expiry first)
        return (b.expiry.year - a.expiry.year) || (b.expiry.month - a.expiry.month)
      })
      logger.log('User has NAKA Cards, using the latest one', { cards })
      await setCard(cards[0])
    }
    cardBlockedCount.value = registration.cards.filter(c => c.status === 'BLOCKED').length
  }

